/* ===== Ядро атласа: модель данных =====
   Содержание лежит в массивах: TH (листы), PG (возбудители), QS (вопросы), FIG (схемы), PH (микрофотографии).
   Формат описан в README.md. Файлы src/*.js наполняют их, app.js рисует. */

const TH = [];   /* листы */
const PG = [];   /* досье возбудителей */
const QS = [];   /* вопросы экзамена */
const FIG = {};  /* схемы и иллюстрации: id → {title, cap, svg | img, src} */
const PH = [];   /* микрофотографии */

/* Лист атласа. T({id, blk:'gen'|'prv', no, title, short, lead, blocks:[...]}) */
function T(o){ o.blocks = o.blocks || []; TH.push(o); return o; }

/* Досье возбудителя. P({id, n, ru, tax, grp, gr, …поля плана ответа…}) — поля см. PLAN_B / PLAN_V ниже.
   Поле — строка (абзац) или массив строк (список). Любое можно не заполнять. */
function P(o){ PG.push(o); return o; }

/* Вопрос экзамена. Q(блок, номер, текст, [id листов], {pg:[id возбудителей], src:'spb'})
   src: 'dent' (по умолчанию) — вопросы из конспекта стоматологического факультета;
        'spb' — экзаменационные вопросы ПСПбГМУ им. И. П. Павлова, лечебный факультет, 2018. */
const QSETS = {
  dent: {name:'Стоматологический', full:'вопросы из файла с ответами, стоматологический факультет'},
  spb:  {name:'ПСПбГМУ 2018',      full:'экзаменационные вопросы ПСПбГМУ им. акад. И. П. Павлова, лечебный факультет, 2018'}
};
function Q(blk, no, text, th, o){ o = o || {}; QS.push({blk, no, text, th: th || [], pg: o.pg || [], src: o.src || 'dent'}); }

/* Схема. F({id, title, cap, svg:'<svg…>'}) — своя схема; F({id, title, cap, img:'img/notes/x.webp', src:'…'}) — из конспекта.
   В листе: {t:'fig', id}. Подписи на схемах — только на русском и латыни. */
function F(o){ FIG[o.id] = o; return o; }

/* Зачёт — кластер тем. Z({id:'z1', no:1, title, topics:['g1','g2','g3'], lead}) задаёт состав и порядок тем.
   Обзорная глава по теме: ZT('g1', {read:'15 мин', blocks:[…]}) — связный текст «как в учебнике»,
   показывается на странице зачёта перед ссылкой на лист для заучивания. Блоки те же, что в листах. */
const ZS = [];   /* зачёты */
const ZTX = {};  /* обзорные главы: id темы → {read, blocks} */
function Z(o){ ZS.push(o); return o; }
function ZT(id, o){ ZTX[id] = o; return o; }

/* Микрофотография. PHOTO({id, file, pg:[…], t:'{Vibrio cholerae}', what:'что видно',
   m:'метод микроскопии', st:'окраска', stShort:'кратко для значка', x:'×1000', au:'автор', lic:'лицензия', src:'URL'})
   В листе: {t:'photos', title, ids:[…]}; в досье снимки подставляются по полю pg. */
function PHOTO(o){ PH.push(o); return o; }

