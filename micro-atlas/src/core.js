/* ===== Ядро атласа: модель данных =====
   Всё содержание атласа лежит в трёх массивах: TH (темы), PG (возбудители), QS (вопросы).
   Формат описан в README.md. Два пробных конспекта поставляются публично; остальные темы, досье и вопросы — в закрытом пакете. */

const TH = [];   /* темы (листы) */
const PG = [];   /* карточки возбудителей */
const QS = [];   /* вопросы экзамена */

/* Тема (лист атласа).
   T({id, blk:'gen'|'prv', no, title, short, lead, blocks:[...]}) */
function T(o){ o.blocks = o.blocks || []; TH.push(o); return o; }

/* Возбудитель.
   P({id, n:'Staphylococcus aureus', ru:'Золотистый стафилококк',
      sp:'вид по ICTV (для вирусов)', syn:'старые названия', tax:'систематика',
      grp:'gpc', gr:'+', fv:'clusters', st:'gram', o2:'факультативный анаэроб',
      tags:['oral'], sum:'одна строка для каталога',
      morph, phys, cult, eco, epi, vir:[], dis:[], dx:[], rx, oral, nb})
   Любое поле досье можно не заполнять — атлас покажет его как незаполненное.
   Поле может быть строкой (абзац) или массивом строк (список). */
function P(o){ PG.push(o); return o; }

/* Вопрос экзамена. Q(блок, номер, текст, [id тем], {pg:[id возбудителей], empty:1}) */
function Q(blk, no, text, th, o){ o = o || {}; QS.push({blk, no, text, th: th || [], pg: o.pg || [], empty: !!o.empty}); }

